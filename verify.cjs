const assert = require('node:assert/strict');
const api = require('./dist/app.js');
const now = new Date(2026, 9, 27, 12).getTime();
const state = api.createState(now);
assert.equal(api.receive(state, { id: 'test', platform: 'iFood', quantity: 2 }, now), true);
assert.equal(api.receive(state, { id: 'test', platform: 'iFood', quantity: 2 }, now), false);
assert.equal(api.receive(state, { id: 'test', platform: 'Rappi', quantity: 1 }, now), true);
const before = state.stock.bacon.qty;
api.advance(state, 'iFood', 'test', now + 1000);
assert.equal(state.stock.bacon.qty, before - 4);
const order = state.orders.find(o => o.id === 'test' && o.platform === 'iFood');
assert.equal(order.stage, 1);
api.advance(state, 'iFood', 'test', now + 2000);
api.advance(state, 'iFood', 'test', now + 3000);
assert.equal(order.stage, 3);
assert.equal(state.stock.bacon.qty, before - 4);
assert.equal(api.advance(state, 'iFood', 'test', now + 4000), false);
const pending = state.orders.find(o => o.id === 'test' && o.platform === 'Rappi');
assert.equal(api.status(pending, now + 95999), 'normal');
assert.equal(api.status(pending, now + 96000), 'attention');
assert.equal(api.status(pending, now + 120000), 'attention');
assert.equal(api.status(pending, now + 120001), 'late');
const m = api.metrics(state, now + 3000);
assert.equal(m.total, 8); assert.equal(m.channels.iFood, 3);
assert.equal(m.average, (720000 + 3000) / 2);
state.stock.pao.qty = 0;
assert.throws(() => api.advance(state, 'Rappi', 'test', now + 4000), /insuficiente/);
assert.equal(pending.stage, 0); assert.equal(pending.stockDeducted, false);
assert.equal(state.stock.bacon.qty, before - 4);
const tomorrow = now + 86400000;
assert.equal(api.metrics(state, tomorrow).total, 0);
assert.equal(api.metrics(state, tomorrow).average, null);
console.log('PASS: duplicidade, etapas, estoque, limites e indicadores.');
